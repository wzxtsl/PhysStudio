"""Build a mechanical graph and leaf sensors from a completed growth state."""
import hashlib
import json
from pathlib import Path
import numpy as np

def prepare(source, cfg):
    source=Path(source)
    growth=json.loads((source/'config.json').read_text())
    file=source/'states'/f"{growth['steps']:05d}.npz"
    with np.load(file) as data:
        original={key:data[key] for key in data.files}
    p=original['p'];parent=original['parent'];shoot=original['kind']==0
    mapping=np.full(len(p),-1,np.int32);ids=[];parents=[]
    for i in np.flatnonzero(shoot):
        par=int(parent[i])
        if par>=0 and np.linalg.norm(p[i]-p[par])<1.e-5:
            mapping[i]=mapping[par]
            continue
        mapping[i]=len(ids);ids.append(i)
        parents.append(-1 if par<0 else int(mapping[par]))
    ids=np.asarray(ids,np.int32);parents=np.asarray(parents,np.int32)
    position=p[ids].astype(np.float32);radius=original['radius'][ids].astype(np.float32)
    edge=np.zeros_like(position);edge[1:]=position[1:]-position[parents[1:]]
    length=np.linalg.norm(edge,axis=1)
    wood_mass=np.pi*radius**2*length*cfg['wood_density']
    # Match the two procedural leaf blades generated by the growth renderer.
    leaf_ids=np.flatnonzero(shoot&((original['order']>=2)|((original['order']==1)&(original['progress']>14))))
    leaf_ids=leaf_ids[growth['steps']-original['birth'][leaf_ids]>.05]
    leaf_ids=np.repeat(leaf_ids,2);side=np.tile([-1,1],len(leaf_ids)//2)
    roll=leaf_ids*2.399963+side*1.35
    direction=np.stack([np.cos(roll),np.sin(roll),.18+.22*np.sin(leaf_ids*1.4)],1)
    direction/=np.linalg.norm(direction,axis=1)[:,None]
    across=np.stack([-np.sin(roll),np.cos(roll),np.zeros(len(leaf_ids))],1)
    normal=np.cross(direction,across);normal/=np.linalg.norm(normal,axis=1)[:,None]
    age=np.maximum(0,growth['steps']-original['birth'][leaf_ids]);unfold=np.minimum(1.,age/7.)
    unfold=unfold*unfold*(3-2*unfold)
    size=growth['leaf_size']*(.8+.25*np.sin(leaf_ids*11.73))*unfold
    samples=np.linspace(0,1,129);width=np.sin(np.pi*samples)**.8*.34
    if growth['leaf_shape']=='oak':width*=.72+.28*np.cos(samples*np.pi*9)
    elif growth['leaf_shape']=='maple':width=np.sin(np.pi*samples)**.7*.50*(.65+.35*np.cos(samples*np.pi*7))
    else:width*=1.+.10*np.cos(samples*np.pi*15)
    area=2*np.trapz(width,samples)*size**2
    owner=mapping[leaf_ids];mass=wood_mass.copy()
    np.add.at(mass,owner,area*cfg['leaf_areal_mass'])
    # Composite subtree inertia about each segment's proximal joint.
    total=mass.astype(np.float64);first=total[:,None]*position
    second=total*np.sum(position**2,axis=1)
    for i in range(len(ids)-1,0,-1):
        par=parents[i];total[par]+=total[i];first[par]+=first[i];second[par]+=second[i]
    pivot=position[np.maximum(parents,0)]
    inertia=(second-2*np.sum(first*pivot,axis=1)+total*np.sum(pivot**2,axis=1))*.65
    inertia=np.maximum(inertia,wood_mass*length**2/3+1.e-8)
    joint_radius=radius.copy();joint_radius[1:]=np.minimum(radius[parents[1:]],radius[1:]*1.25)
    stiffness=cfg['young']*np.pi*joint_radius**4/(4*np.maximum(length,.01))
    damping=2*cfg['damping_ratio']*np.sqrt(stiffness*inertia)
    leaf_inertia=cfg['leaf_areal_mass']*area*size**2/3
    # Petiole dimensions scale with the blade rather than using a single angle animation.
    leaf_k=cfg['leaf_stiffness']*(size/.18)**2
    leaf_c=2*cfg['leaf_damping']*np.sqrt(np.maximum(leaf_inertia*leaf_k,1.e-16))
    asset=dict(ids=ids,parent=parents,mapping=mapping,position=position,edge=edge,
               radius=radius,length=length,mass=mass,inertia=inertia,stiffness=stiffness,damping=damping,
               leaf_ids=leaf_ids,leaf_owner=owner,leaf_direction=direction,leaf_across=across,
               leaf_normal=normal,leaf_size=size,leaf_area=area,leaf_unfold=unfold,
               leaf_inertia=leaf_inertia,leaf_stiffness=leaf_k,leaf_damping=leaf_c)
    provenance=dict(source=str(source.resolve()),state_sha256=hashlib.sha256(file.read_bytes()).hexdigest(),
                    original_nodes=len(p),mechanical_nodes=len(ids),leaf_blades=len(owner))
    return asset,original,growth,provenance
